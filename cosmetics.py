COLOR_VALUES = {"default", "random", "auto", *COLORS}


class Cosmetics(OptionDict):
    """
    OoTMM cosmetics, applied when the host builds your ROM. True/false: defaultHold (Z-targeting on Hold),
    applyFreestandings, musicNames, musicCategories, nightBgm, noLowHealthBeep, gerudoTunic. Colors (an OoTMM color
    name, default, random or auto): ootTunicKokiri, ootTunicGoron, ootTunicZora, ootShieldMirror, mmTunicHuman,
    mmTunicDeku, mmTunicGoron, mmTunicZora, mmTunicFierceDeity, dpad, fileSelect.
    """
    display_name = "Cosmetics"
    valid_keys = frozenset(BOOLEANS) | frozenset(COLOR_TARGETS)
    default = {}

    def __init__(self, value):
        for key, setting in value.items():
            if key in BOOLEANS and not isinstance(setting, bool):
                raise ValueError(f"Cosmetic {key} must be true or false, not {setting!r}")
            if key in COLOR_TARGETS and setting not in COLOR_VALUES:
                raise ValueError(f"Unknown color {setting!r} for cosmetic {key}")
        super().__init__(value)
